/**
 * Builds src/osm-patan.js: building footprints, the brick plaza and the streets of
 * Patan Durbar Square from OpenStreetMap, for the "Newa Parchment Blueprint" map layer.
 *
 *   node scripts/osm-patan.mjs            fetch from the Overpass API
 *   node scripts/osm-patan.mjs data.json  use a saved Overpass response (out geom)
 *
 * Map data © OpenStreetMap contributors, available under the ODbL.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const BBOX = '27.6725,85.3242,27.6740,85.3257';
const QUERY = `[out:json][timeout:60];(
  way(${BBOX})["building"]; relation(${BBOX})["building"];
  way(${BBOX})["highway"]; way(${BBOX})["leisure"]; way(${BBOX})["landuse"];
);out geom tags;`;
const SERVERS = ['https://overpass.kumi.systems/api/interpreter', 'https://overpass-api.de/api/interpreter'];

async function fetchOverpass() {
  for (const url of SERVERS) {
    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'User-Agent': 'mandala-quest-build/0.1', 'Content-Type': 'application/x-www-form-urlencoded' },
        body: `data=${encodeURIComponent(QUERY)}`,
      });
      if (res.ok) return await res.json();
    } catch {
      /* try the next server */
    }
  }
  throw new Error('No Overpass server answered.');
}

const data = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : await fetchOverpass();

const round = (v) => Math.round(v * 1e7) / 1e7;
const ring = (geom) => geom.map((p) => [round(p.lon), round(p.lat)]);

function classify(t) {
  if (t.highway === 'pedestrian' && t.area === 'yes') return 'plaza';
  if (t.highway) return ['secondary', 'tertiary'].includes(t.highway) ? 'street' : ['residential', 'service'].includes(t.highway) ? 'lane' : 'path';
  if (t.historic === 'monument') return 'plinth'; // e.g. the Taleju Bell's stand
  if (t.historic || t.building === 'gatehouse') return 'palace';
  if (t.amenity === 'place_of_worship' || t.building === 'temple') return 'temple';
  if (t.building === 'column') return 'column';
  if (t.building === 'steps') return 'plinth';
  if (t.leisure === 'common') return 'plinth';
  if (t.leisure === 'park' || t.landuse === 'grass') return 'green';
  if (t.landuse === 'basin') return 'water';
  if (t.building || t.landuse) return 'house';
  return null;
}

const features = [];
for (const e of data.elements) {
  const t = e.tags || {};
  const kind = classify(t);
  if (!kind) continue;
  const f = { kind, id: `${e.type[0]}${e.id}` };
  const name = t['name:en'] || t.name;
  if (name && (kind === 'street' || kind === 'lane' || kind === 'palace')) f.name = name;
  if (e.type === 'relation') {
    const members = (e.members || []).filter((m) => m.geometry);
    if (!members.length) continue;
    f.rings = members.map((m) => ring(m.geometry));
  } else if (['street', 'lane', 'path'].includes(kind)) {
    f.line = ring(e.geometry);
  } else {
    f.rings = [ring(e.geometry)];
  }
  features.push(f);
}

// Draw order: ground first, then streets, then buildings.
const ORDER = ['green', 'water', 'plinth', 'plaza', 'street', 'lane', 'path', 'house', 'temple', 'palace', 'column'];
features.sort((a, b) => ORDER.indexOf(a.kind) - ORDER.indexOf(b.kind));

const out = `// Generated by scripts/osm-patan.mjs — do not edit by hand.
// Map data © OpenStreetMap contributors, available under the Open Database License (ODbL).
// Points are [lon, lat]. Polygons are lists of rings; relations keep their courtyards as inner rings.

export const OSM_ATTRIBUTION = '© OpenStreetMap contributors';

export const OSM_FEATURES = ${JSON.stringify(features)};
`;
writeFileSync(new URL('../src/osm-patan.js', import.meta.url), out);
console.log(`Wrote ${features.length} features to src/osm-patan.js`);
